#!/usr/bin/env python3
"""Derive product lists from the existing upstream rules without changing rules."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
# Product identifiers, not a second inventory of websites. Unknown entries stay AI.
PRODUCTS = {
    'GoogleAI': ('google', 'antigravity'),
    'GPT': ('openai', 'chatgpt', 'oaistatic', 'oaiusercontent', 'sora'),
    'Claude': ('anthropic', 'claude', 'clau'),
    'AnyRouter': ('anyrouter',),
}


def parse_rules(text):
    rules = []
    for raw in text.splitlines():
        rule = raw.strip()
        if not rule or rule.startswith('#'):
            continue
        kind, comma, value = rule.partition(',')
        if kind not in ('DOMAIN', 'DOMAIN-SUFFIX', 'DOMAIN-KEYWORD') or not comma or not value or ',' in value or any(c.isspace() for c in value):
            raise ValueError('Upstream rule format changed; existing output is retained')
        if rule not in rules:
            rules.append(rule)
    if not rules:
        raise ValueError('Empty upstream rules; existing output is retained')
    return rules


def product(rule):
    value = rule.partition(',')[2].lower()
    matches = [name for name, tokens in PRODUCTS.items() if any(token in value for token in tokens)]
    # Ambiguous new entries remain in the original AI fallback rather than guessing.
    return matches[0] if len(matches) == 1 else 'AI'


def split_rules(rules):
    groups = {name: [] for name in (*PRODUCTS, 'AI')}
    for rule in rules:
        groups[product(rule)].append(rule)
    flattened = [rule for values in groups.values() for rule in values]
    if len(flattened) != len(set(flattened)) or set(flattened) != set(rules):
        raise ValueError('Rule partition lost or duplicated input')
    if any(not groups[name] for name in PRODUCTS):
        raise ValueError('A product list is empty; existing output is retained')
    return groups


def source_url(config, name):
    block = re.search(r'(?m)^  ' + re.escape(name) + r':\n((?:    [^\n]*\n)+)', config)
    url = re.search(r'(?m)^    url: (\S+)\s*$', block[1]) if block else None
    if not url or not url[1].startswith('https://'):
        raise ValueError('Cannot read the existing provider URL: ' + name)
    return url[1]


def fetch(url):
    request = urllib.request.Request(url, headers={'User-Agent': 'ash-ai-rule-updater', 'Cache-Control': 'no-cache'})
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    with opener.open(request, timeout=30) as response:
        return response.read(1024 * 1024).decode('utf-8-sig')


def build(config, upstream, legacy, extras):
    original = parse_rules(upstream)
    old_openai = parse_rules(legacy)
    extra = parse_rules(extras)
    combined = list(dict.fromkeys(original + extra))
    groups = split_rules(combined)
    outputs = {}
    for name in PRODUCTS:
        outputs['AI-' + name + '.list'] = (
            '# Generated by scripts/update-ai-lists.py; edit upstream or AI-Extra.list.\n'
            '# Source: ' + source_url(config, 'AI') + '\n'
            + '\n'.join(groups[name]) + '\n'
        )
    original_coverage = set(original + old_openai + extra)
    resulting_coverage = set(rule for values in groups.values() for rule in values) | set(old_openai)
    if resulting_coverage != original_coverage:
        raise ValueError('Original coverage was not preserved')
    report = {
        'source_url': source_url(config, 'AI'),
        'legacy_openai_url': source_url(config, 'OpenAi'),
        'source_sha256': hashlib.sha256(upstream.encode()).hexdigest(),
        'upstream_rules': len(original), 'legacy_openai_rules': len(old_openai),
        'extra_rules': len(extra), 'counts': {name: len(values) for name, values in groups.items()},
        'remaining_AI': groups['AI'], 'missing': [], 'unexpected': [],
        'coverage': 'All original rules retain their exact match type and value; original AI/OpenAi providers remain as fallbacks.',
    }
    outputs['AI-Coverage.json'] = json.dumps(report, ensure_ascii=False, indent=2) + '\n'
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-file', type=Path, help='Offline upstream snapshot for validation')
    parser.add_argument('--openai-file', type=Path, help='Offline OpenAi snapshot for validation')
    parser.add_argument('--output-root', type=Path, default=ROOT)
    args = parser.parse_args()
    config = (ROOT / 'config.yaml').read_text()
    upstream = args.source_file.read_text() if args.source_file else fetch(source_url(config, 'AI'))
    legacy = args.openai_file.read_text() if args.openai_file else fetch(source_url(config, 'OpenAi'))
    outputs = build(config, upstream, legacy, (ROOT / 'Rullset/AI-Extra.list').read_text())
    # All fetches, parsing and coverage checks finish before touching any output.
    target = args.output_root / 'Rullset'
    target.mkdir(parents=True, exist_ok=True)
    for name, content in outputs.items():
        temporary = target / (name + '.tmp')
        temporary.write_text(content)
        temporary.replace(target / name)
    print(outputs['AI-Coverage.json'])


if __name__ == '__main__':
    main()
